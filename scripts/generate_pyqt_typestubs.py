"""Generate pyright override stubs for qgis.PyQt's wildcard re-exports.

qgis/PyQt/QtCore.py (and its siblings) do ``from PyQt6.QtCore import *`` to
transparently support both Qt5 and Qt6 QGIS builds at runtime. Pyright
deliberately refuses to populate a module's exported symbol table from a
wildcard import of a third-party library (``reportWildcardImportFromLibrary``
is about the diagnostic, but the symbol-table gap applies regardless of that
diagnostic's severity) - so every name reached only through ``qgis.PyQt.*``
(QVariant, pyqtSignal, QColor, ...) is "unknown import symbol" to pyright.

This script regenerates small `typings/qgis/PyQt/<Module>.pyi` overrides
that explicitly re-export (``from PyQtX.Module import Name as Name``) every
public name the real Qt binding currently provides, so pyright can resolve
them. It inspects the *active* interpreter's qgis.PyQt shim to discover
which submodules need an override and which real PyQt package (5 or 6)
they forward to, so it tracks whichever QGIS/Qt variant is on PYTHONPATH.
"""

import importlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TYPINGS_ROOT = REPO_ROOT / "typings"

HEADER = "# Auto-generated by scripts/generate_pyqt_typestubs.py - do not edit by hand.\n"


def real_pyqt_target(shim_source: str) -> str | None:
    """Return the "PyQtX.Module" a qgis/PyQt/<Module>.py wildcard-imports, if any."""
    for line in shim_source.splitlines():
        line = line.strip()
        if line.startswith("from PyQt") and " import *" in line:
            return line.split("from ", 1)[1].split(" import", 1)[0].strip()
    return None


def public_names(module) -> list[str]:
    names = getattr(module, "__all__", None)
    if names is None:
        names = [n for n in dir(module) if not n.startswith("_")]
    return sorted(names)


def main() -> int:
    try:
        pyqt_pkg = importlib.import_module("qgis.PyQt")
    except ImportError:
        print("qgis.PyQt is not importable in this interpreter - skipping stub generation.")
        return 0

    assert pyqt_pkg.__file__ is not None
    shim_dir = Path(pyqt_pkg.__file__).resolve().parent
    out_dir = TYPINGS_ROOT / "qgis" / "PyQt"
    out_dir.mkdir(parents=True, exist_ok=True)
    # Deliberately no qgis/__init__.pyi or qgis/PyQt/__init__.pyi here: once
    # pyright finds a stub __init__ for a package it stops merging that
    # package's *other* submodules in from the real source tree (e.g.
    # `from qgis import processing` or `from qgis.PyQt import uic` would
    # start failing even though neither is touched by this script).

    generated = []
    for shim_file in sorted(shim_dir.glob("*.py")):
        if shim_file.name == "__init__.py":
            continue
        target = real_pyqt_target(shim_file.read_text(encoding="utf-8"))
        if target is None:
            continue

        try:
            real_module = importlib.import_module(target)
        except ImportError as exc:
            print(f"skipping {shim_file.name}: cannot import {target} ({exc})")
            continue

        names = public_names(real_module)
        lines = [HEADER, f"from {target} import (\n"]
        lines += [f"    {name} as {name},\n" for name in names]
        lines.append(")\n")

        stub_path = out_dir / f"{shim_file.stem}.pyi"
        stub_path.write_text("".join(lines), encoding="utf-8")
        generated.append(stub_path.relative_to(REPO_ROOT))

    print(f"Generated {len(generated)} pyright override stub(s) under {out_dir.relative_to(REPO_ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
